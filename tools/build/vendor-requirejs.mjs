/**
 * Writes RequireJS, minified, as a string module into the portable-custom-interaction package.
 *
 * Why this exists: every PCI runs in its own srcdoc iframe, and a PCI module is an AMD module, so that iframe needs
 * RequireJS. It used to load it from cdnjs (and the whole qti-components bundle from unpkg), so every player depended
 * on public CDNs. Inlining the loader as text needs it as a string at runtime, and `?raw` is bundler-only syntax that
 * tsc copies through verbatim (see css-text-module.mjs), so the string is a real source file instead: generated from
 * the pinned `requirejs` devDependency, checked in, and compiled by tsc like any other module.
 *
 * Usage: node tools/build/vendor-requirejs.mjs   (rerun after bumping `requirejs`)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const pkgDir = path.join(root, 'packages/interactions/portable-custom-interaction');
const require = createRequire(path.join(pkgDir, 'package.json'));
// esbuild is not a direct dependency of the root; it is the one tsup (a root devDependency) builds with.
const { transformSync } = createRequire(createRequire(path.join(root, 'package.json')).resolve('tsup'))('esbuild');

const sourcePath = require.resolve('requirejs/require.js');
const { version } = JSON.parse(readFileSync(path.join(path.dirname(sourcePath), 'package.json'), 'utf8'));

// Minify only: the file is plain ES5 and must stay a classic script (it defines the `require`/`define` globals).
// `legalComments: 'inline'` keeps the @license header.
const { code } = transformSync(readFileSync(sourcePath, 'utf8'), {
  minify: true,
  legalComments: 'inline',
  loader: 'js'
});

const out = path.join(pkgDir, 'src/vendor/require-js.ts');
writeFileSync(
  out,
  `// Generated by tools/build/vendor-requirejs.mjs from requirejs ${version} (MIT, https://requirejs.org) - do not edit.\n` +
    `export const requireJsVersion = ${JSON.stringify(version)};\n` +
    `export default ${JSON.stringify(code.trim())};\n`
);

console.log(`vendor-requirejs: requirejs ${version} -> ${path.relative(root, out)} (${code.length} chars)`);
